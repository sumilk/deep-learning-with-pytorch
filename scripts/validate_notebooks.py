"""Execute course notebooks from a fresh kernel and record the results.

Two checks run for every notebook:

- **Solution notebook** (``solutions/``): every cell must run without error.
- **Student notebook** (``notebooks/``): every teaching cell must run. Only
  cells tagged ``exercise`` or ``check`` may fail, and only with
  ``NotImplementedError`` or ``NameError`` (the unfinished-exercise stubs).
  This proves teaching cells never depend on a learner's exercise answers.

Results are written to ``VALIDATION.md``.

Usage:

    uv run python scripts/validate_notebooks.py                 # everything
    uv run python scripts/validate_notebooks.py ch01_foundations
    uv run python scripts/validate_notebooks.py ch01_foundations --match 01_ --no-report
    DLCOURSE_DEVICE=cpu uv run python scripts/validate_notebooks.py
"""

import argparse
import datetime
import platform
import sys
import time
from pathlib import Path

import nbformat
import torch
from nbclient import NotebookClient
from nbclient.exceptions import CellExecutionError

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from dlcourse.device import get_device  # noqa: E402

ALLOWED_STUDENT_ERRORS = {"NotImplementedError", "NameError"}


def run(path, allow_errors, timeout):
    nb = nbformat.read(path, as_version=4)
    client = NotebookClient(
        nb,
        timeout=timeout,
        kernel_name="python3",
        allow_errors=allow_errors,
        resources={"metadata": {"path": str(path.parent)}},
    )
    start = time.perf_counter()
    try:
        client.execute()
    except CellExecutionError as error:
        return False, time.perf_counter() - start, str(error).strip().splitlines()[-1]
    elapsed = time.perf_counter() - start
    if not allow_errors:
        return True, elapsed, ""
    problems = []
    for index, cell in enumerate(nb.cells):
        if cell.cell_type != "code":
            continue
        tags = set(cell.metadata.get("tags", []))
        for output in cell.get("outputs", []):
            if output.get("output_type") != "error":
                continue
            ename = output.get("ename")
            if not tags & {"exercise", "check"}:
                problems.append(f"cell {index}: teaching cell raised {ename}")
            elif ename not in ALLOWED_STUDENT_ERRORS:
                problems.append(f"cell {index}: exercise stub raised {ename}")
    return not problems, elapsed, "; ".join(problems)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("chapters", nargs="*", help="chapter folders to run (default: all)")
    parser.add_argument("--timeout", type=int, default=900, help="per-cell timeout in seconds")
    parser.add_argument("--match", default="", help="only run notebooks whose file name contains this text")
    parser.add_argument("--no-report", action="store_true", help="do not rewrite VALIDATION.md")
    args = parser.parse_args()

    chapters = args.chapters or sorted(p.name for p in (ROOT / "solutions").iterdir() if p.is_dir())
    rows = []
    failures = 0
    for chapter in chapters:
        for solution in sorted((ROOT / "solutions" / chapter).glob("*.ipynb")):
            if args.match not in solution.name:
                continue
            student = ROOT / "notebooks" / chapter / solution.name
            for variant, path, allow in (("solution", solution, False), ("student", student, True)):
                ok, elapsed, detail = run(path, allow, args.timeout)
                failures += not ok
                status = "pass" if ok else "FAIL"
                print(f"{status:4}  {elapsed:6.1f}s  {variant:8}  {chapter}/{path.name}  {detail}")
                rows.append((chapter, path.name, variant, status, elapsed, detail))

    if not args.no_report:
        write_report(rows)
    print(f"\n{len(rows) - failures}/{len(rows)} notebook runs passed.")
    sys.exit(1 if failures else 0)


def write_report(rows):
    device = get_device()
    hardware = f"{platform.system()} {platform.machine()}"
    if device.type == "cuda":
        hardware += f", {torch.cuda.get_device_name(0)}"
    lines = [
        "# Validation results",
        "",
        "Generated by `scripts/validate_notebooks.py`. Each notebook is executed from a fresh kernel.",
        "",
        f"- Date: {datetime.date.today().isoformat()}",
        f"- Python {platform.python_version()}, PyTorch {torch.__version__}",
        f"- Hardware: {hardware}; selected device: `{device}`",
        "",
        "| Chapter | Notebook | Variant | Status | Runtime (s) | Notes |",
        "| --- | --- | --- | --- | ---: | --- |",
    ]
    for chapter, name, variant, status, elapsed, detail in rows:
        lines.append(f"| {chapter} | {name} | {variant} | {status} | {elapsed:.1f} | {detail} |")
    (ROOT / "VALIDATION.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
